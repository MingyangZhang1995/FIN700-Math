#| fig-align: center
import matplotlib.pyplot as plt
from matplotlib.patches import FancyBboxPatch, FancyArrowPatch

# Create a clean diagram that can be pasted into Quarto/Python workflows
fig, ax = plt.subplots(figsize=(8, 6))
ax.set_xlim(0, 12.2)
ax.set_ylim(0, 8.2)
ax.axis("off")

# Box settings
box_w, box_h = 2, 2
left_x, right_x = 0.1, 10.4
top_y, bottom_y = 3.2, 0.1

def add_box(x, y, label):
    box = FancyBboxPatch(
        (x, y), box_w, box_h,
        boxstyle="round,pad=0.02",
        linewidth=2,
        facecolor="white",
        edgecolor="black"
    )
    ax.add_patch(box)
    ax.text(x + box_w/2, y + box_h/2, label,
            ha="center", va="center", fontsize=16)

add_box(left_x, top_y, "S")
add_box(right_x, top_y, "S(1 + r_f)")
add_box(left_x, bottom_y, "1 Share Disney")
add_box(right_x, bottom_y, "1 Share Disney")

def connect(p1, p2, text, text_offset=(0, 0)):
    arrow = FancyArrowPatch(
        p1, p2,
        arrowstyle="->",
        mutation_scale=18,
        linewidth=2,
        color="black"
    )
    ax.add_patch(arrow)
    mx = (p1[0] + p2[0]) / 2 + text_offset[0]
    my = (p1[1] + p2[1]) / 2 + text_offset[1]
    ax.text(mx, my, text, ha="center", va="center", fontsize=13)

# Horizontal and vertical connections
connect((left_x + box_w, top_y + box_h/2), (right_x, top_y + box_h/2), r"$r_f$" + "\nHold for 1 year\n(saving)", (0, 0.2))
connect((left_x + box_w, bottom_y + box_h/2), (right_x, bottom_y + box_h/2), "Hold for 1 year\n(Stock)", (0, 0.2))
connect((left_x + box_w/2, top_y), (left_x + box_w/2, bottom_y + box_h), "-S", (-0.4, 0))
connect((right_x + box_w/2, bottom_y + box_h), (right_x + box_w/2, top_y), "+F", (0.35, 0))

plt.tight_layout()
plt.show()
