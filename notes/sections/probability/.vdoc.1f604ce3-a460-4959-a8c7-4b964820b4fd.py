import numpy as np
import matplotlib.pyplot as plt

# Plot the PDF of a Uniform(0,1) distribution
x = np.linspace(-0.5, 1.5, 100)
pdf = np.where((x >= 0) & (x <= 1), 1, 0)
plt.plot(x, pdf, label='PDF of Uniform(0,1)')
plt.fill_between(x, pdf, alpha=0.2)
plt.xlabel('x')
plt.ylabel('PDF')
plt.show()
